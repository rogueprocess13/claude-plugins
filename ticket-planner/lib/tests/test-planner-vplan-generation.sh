#!/usr/bin/env bash
# test-planner-vplan-generation.sh — planner-ready-by-construction.
#
# Shape tests against the REAL ticket-auto-pipeline vplan-parse.sh, not an
# LLM-output test: proves the table shape TicketGen's prompt instructs is
# genuinely parseable by the parser it will be scored against, not just
# plausible-looking prose. Also asserts Specify's own example Verification
# Notes table, run through planner_ticketgen_vplan (#499), round-trips
# through the real parser — a drift between the two would mean the prompt is
# teaching an agent to fail its own downstream check.
#
# Run: bash ticket-planner/lib/tests/test-planner-vplan-generation.sh

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
LIB_DIR="${SCRIPT_DIR}/.."
VPLAN_PARSE="${LIB_DIR}/../../ticket-auto-pipeline/lib/vplan-parse.sh"

if [ ! -f "$VPLAN_PARSE" ]; then
  echo "SKIP: ticket-auto-pipeline/lib/vplan-parse.sh not found at ${VPLAN_PARSE} (sibling checkout only)"
  exit 0
fi

source "$VPLAN_PARSE"
source "${LIB_DIR}/planner-phase-prompts.sh"

PASS=0
FAIL=0
pass() {
  echo "  PASS $1"
  PASS=$((PASS + 1))
}
fail() {
  echo "  FAIL $1: $2"
  FAIL=$((FAIL + 1))
}

echo "=== planner-vplan-generation tests ==="

echo "--- a body matching the instructed shape parses cleanly ---"

synthetic_body='## Acceptance Criteria
- [ ] The export button appears on the invoice list
- [ ] The exported file reflects the current filter

## Verification Plan

### Per-Criterion Verification

| # | Criterion | Role scope | Navigation path | Test data needed | Expected behavior | Verifiable |
|---|-----------|-----------|------------------|-------------------|--------------------|------------|
| 1 | Export button appears | finance | Billing > Invoices | none | button is visible | Y |
| 2 | Export reflects filter | finance | Billing > Invoices | 5 seeded invoices, 2 matching filter | downloaded file has exactly 2 rows | Y |
'

if vplan_parse "$synthetic_body"; then
  pass "vplan_parse accepts the instructed table shape"
else
  fail "vplan_parse accepts the instructed table shape" "returned nonzero"
fi
if [ "${VPLAN_ROWS:-0}" -eq 2 ]; then
  pass "VPLAN_ROWS == 2 (one per AC line)"
else
  fail "VPLAN_ROWS == 2" "got ${VPLAN_ROWS:-unset}"
fi
if [ "${VPLAN_VERIFIABLE:-0}" -eq 2 ]; then
  pass "VPLAN_VERIFIABLE == 2 (both rows marked Y)"
else
  fail "VPLAN_VERIFIABLE == 2" "got ${VPLAN_VERIFIABLE:-unset}"
fi

echo "--- a row left honestly blank still parses and counts toward the row total ---"

# vplan-parse.sh reads only the Verifiable column (#514), so the blank row's
# "any agency user" prose (full of y) must not count as a mark.
mixed_body='## Verification Plan

### Per-Criterion Verification

| # | Criterion | Role scope | Navigation path | Test data needed | Expected behavior | Verifiable |
|---|-----------|-----------|------------------|-------------------|--------------------|------------|
| 1 | Screen shows no clutter | any agency user | n/a | none | requires human judgment |   |
| 2 | Export downloads a CSV | finance | Billing > Invoices | none | invoices.csv downloaded | Y |
'
if vplan_parse "$mixed_body" && [ "${VPLAN_ROWS:-0}" -eq 2 ] && [ "${VPLAN_VERIFIABLE:-0}" -eq 1 ]; then
  pass "an honest blank Verifiable cell still parses; only the marked row counts"
else
  fail "an honest blank Verifiable cell still parses; only the marked row counts" "rows=${VPLAN_ROWS:-unset} verifiable=${VPLAN_VERIFIABLE:-unset}"
fi

echo "--- Specify's own example Verification Notes table → generator → real parser (#499) ---"

# Since #499 TicketGen no longer shows the agent a table to mirror: the table
# is generated by planner_ticketgen_vplan from Specify's Verification Notes.
# Take the example notes table straight out of the rendered Specify prompt,
# pair it with ACs whose text matches its Criterion cells, and prove the
# generated section parses with one row per AC and the right ✓ count.
source "${LIB_DIR}/planner-ticket-body.sh"
specify_prompt=$(planner_prompt_specify "INIT-TEST" "an idea" "/repos/.ticket-auto/initiatives/INIT-TEST")
notes_table=$(awk '
  /^## Verification Notes$/ { grab = 1; print; next }
  grab && /^```$/ { exit }
  grab { print }
' <<<"$specify_prompt")
ac_lines=$(grep -E '^\| [^|-]' <<<"$notes_table" | grep -v '^| Criterion ' | cut -d'|' -f2 |
  sed -E 's/^ +//; s/ +$//; s/^/- [ ] /')

tmp_spec=$(mktemp)
printf '## Acceptance Criteria\n\n%s\n\n%s\n' "$ac_lines" "$notes_table" >"$tmp_spec"
generated=$(planner_ticketgen_vplan "$tmp_spec" 2>/dev/null)
rm -f "$tmp_spec"

ac_count=$(grep -c '^- \[ \]' <<<"$ac_lines")
if [ "$ac_count" -ge 2 ] && vplan_parse "$generated" && [ "${VPLAN_ROWS:-0}" -eq "$ac_count" ]; then
  pass "Specify's example notes generate a parseable table, one row per AC (${ac_count})"
else
  fail "Specify's example notes generate a parseable table" "acs=${ac_count} rows=${VPLAN_ROWS:-unset} generated=${generated}"
fi
marks=$(grep -c '| ✓ |$' <<<"$generated")
yes_rows=$(grep -cE '\| yes \|$' <<<"$notes_table")
if [ "$marks" -eq "$yes_rows" ] && [ "$marks" -ge 1 ]; then
  pass "only the rows the notes mark verifiable get ✓ (${marks})"
else
  fail "✓ marks follow the notes" "marks=${marks} yes_rows=${yes_rows}"
fi

echo ""
echo "=== Results: $PASS passed, $FAIL failed ==="
[ "$FAIL" -eq 0 ]
